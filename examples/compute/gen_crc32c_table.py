"""Write crc32c_table.h: the CRC32C (Castagnoli, reflected 0x82F63B78) tables.

Row 0 is the bytewise table: entry i is the raw update of byte i from 0.
Row k is the raw update of byte i followed by k zero bytes, the slice-by-8
construction  T[k][i] = (T[k-1][i] >> 8) ^ T[0][T[k-1][i] & 0xff].
usage: gen_crc32c_table.py OUT
"""
import sys

POLY = 0x82F63B78


def rows():
    t0 = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ POLY if c & 1 else c >> 1
        t0.append(c)
    table = [t0]
    for _ in range(7):
        prev = table[-1]
        table.append([(v >> 8) ^ t0[v & 0xFF] for v in prev])
    return table


def row_macro(k, row):
    lines = [f'#define EX_CRC32C_ROW{k} \\']
    for start in range(0, 256, 6):
        chunk = ', '.join(f'0x{v:08x}' for v in row[start:start + 6])
        end = ',' if start + 6 < 256 else ''
        lines.append(f'\t{chunk}{end} \\' if end else f'\t{chunk}')
    return '\n'.join(lines)


def header():
    table = rows()
    out = ['/* SPDX-License-Identifier: GPL-2.0 */',
           '/* Generated by gen_crc32c_table.py; do not edit. */',
           '#ifndef EX_CRC32C_TABLE_H',
           '#define EX_CRC32C_TABLE_H',
           '',
           '/*',
           ' * CRC32C (Castagnoli, reflected polynomial 0x82F63B78) lookup tables.',
           ' * Row 0 is the bytewise table (1 KiB); rows 0..7 are the slice-by-8',
           ' * tables (8 KiB). Row k, entry i: the raw update of byte i followed by',
           ' * k zero bytes, starting from 0. Define EX_CRC32C_SLICE8 to 0 or 1.',
           ' */',
           '']
    for k, row in enumerate(table):
        out.append(row_macro(k, row))
        out.append('')
    out += ['#if EX_CRC32C_SLICE8',
            '#define EX_CRC32C_ROWS 8',
            'static const __u32 ex_crc32c_tab[EX_CRC32C_ROWS][256] = {',
            '\t{ EX_CRC32C_ROW0 }, { EX_CRC32C_ROW1 }, { EX_CRC32C_ROW2 }, { EX_CRC32C_ROW3 },',
            '\t{ EX_CRC32C_ROW4 }, { EX_CRC32C_ROW5 }, { EX_CRC32C_ROW6 }, { EX_CRC32C_ROW7 },',
            '};',
            '#else',
            '#define EX_CRC32C_ROWS 1',
            'static const __u32 ex_crc32c_tab[EX_CRC32C_ROWS][256] = {',
            '\t{ EX_CRC32C_ROW0 },',
            '};',
            '#endif',
            '',
            '#endif',
            '']
    return '\n'.join(out)


def main():
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    with open(sys.argv[1], 'w') as fh:
        fh.write(header())
    return 0


if __name__ == '__main__':
    sys.exit(main())
