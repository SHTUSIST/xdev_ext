"""Search tracked canonical test code without running tests or building source views."""
import argparse
import ast
import json
from pathlib import Path
import re
import subprocess
import sys

from layout import LayoutError, load_layout, safe_file

HEADER_LIMIT = 16384
PYTHON_LIMIT = 262144
ROLES = ('entry', 'fixture', 'documentation', 'build', 'unknown')
INDEX_MARKER = '# Test code index\n\nGenerated by `python3 tools/test_catalog.py write-index`'


def tracked_tests(repo):
    result = subprocess.run(['git', '-C', str(repo), 'ls-files', '-z', '--', 'tests'],
                            check=True, capture_output=True)
    return sorted(set(result.stdout.decode().rstrip('\0').split('\0')) - {''})


def read_prefix(path, limit=HEADER_LIMIT):
    with path.open('rb') as stream:
        return stream.read(limit).decode('utf-8', errors='replace')


def header_title(path, text):
    """Return a literal first description line, never an inferred purpose."""
    if path.suffix == '.py':
        # A module docstring may follow shebang, encoding and license comments.
        prefix = re.sub(r'\A(?:\s*#[^\n]*\n|\s*\n)*', '', text)
        match = re.match(r'(?:[ruRU])?("""|\'\'\')(.*?)\1', prefix, re.S)
        if match:
            lines = match.group(2).strip().splitlines()
            if lines:
                return lines[0].strip()[:240]
    if path.suffix.lower() == '.md':
        match = re.search(r'^# +(.+)$', text, re.M)
        return match.group(1).strip()[:240] if match else None
    # Only initial comments count; do not turn arbitrary code into prose.
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith(('#!', '*/')):
            continue
        if any(suffix.lower() in ('.c', '.h', '.cc', '.cpp', '.cxx', '.hpp', '.cu', '.cuh')
               for suffix in path.suffixes) and line.startswith('#'):
            break
        if line.startswith(('/*', '#', '//', '*')):
            candidate = re.sub(r'^(?:/\*|//|#|\*)\s*', '', line)
            candidate = candidate.split('*/', 1)[0].strip()
            if not candidate or 'SPDX-License-Identifier:' in candidate or candidate.lower().startswith(('copyright', 'coding:', '-*-')):
                continue
            return candidate[:240]
        break
    return None


def role_for(name, text, path):
    parts = Path(name).parts
    stem = path.stem
    if any(p in ('fixture', 'fixtures') for p in parts) or ('fixture' in stem and not stem.startswith('test_') and not stem.endswith('_test')):
        return 'fixture'
    if path.suffix.lower() == '.md':
        return 'documentation'
    if path.name in ('Makefile', 'Kbuild', 'CMakeLists.txt'):
        return 'build'
    if path.suffix == '.sh' and text.startswith('#!'):
        return 'entry'
    if path.suffix == '.py' and path.stat().st_size <= PYTHON_LIMIT:
        try:
            tree = ast.parse(read_prefix(path, PYTHON_LIMIT))
        except (SyntaxError, ValueError):
            return 'unknown'
        for node in tree.body:
            if isinstance(node, ast.If):
                condition = node.test
                if (isinstance(condition, ast.Compare) and isinstance(condition.left, ast.Name)
                        and condition.left.id == '__name__' and len(condition.ops) == 1
                        and isinstance(condition.ops[0], ast.Eq)
                        and isinstance(condition.comparators[0], ast.Constant)
                        and condition.comparators[0].value == '__main__'):
                    return 'entry'
    return 'unknown'


def build_catalog(repo):
    repo = Path(repo).resolve()
    safe_file(repo, 'source-layout.json')
    top = subprocess.run(['git', '-C', str(repo), 'rev-parse', '--show-toplevel'],
                         check=True, capture_output=True, text=True).stdout.strip()
    if Path(top).resolve() != repo:
        raise LayoutError('--repo must be the canonical Git repository root')
    layout = load_layout(repo)
    names = tracked_tests(repo)
    tracked = set(names)
    records = []
    for name in names:
        path = safe_file(repo, name)
        text = read_prefix(path)
        title = header_title(path, text)
        title_source = name if title else None
        if not title:
            for directory in (path.parent, *path.parent.parents):
                if directory == repo:
                    break
                readme = (directory / 'README.md').relative_to(repo).as_posix()
                if readme in tracked:
                    title = header_title(Path(readme), read_prefix(safe_file(repo, readme)))
                    if title:
                        title_source = readme
                        break
        records.append({'canonical_path': name,
                        'logical_path': layout.by_source.get(name),
                        'module': Path(name).parts[1] if len(Path(name).parts) > 2 else 'tests',
                        'role': role_for(name, text, path),
                        'title': title or path.name,
                        'title_source': title_source})
    metadata = 'tests/test_catalog/entries.json'
    if metadata in tracked:
        apply_metadata(repo, records, tracked, metadata)
    return records


def apply_metadata(repo, records, tracked, metadata):
    path = safe_file(repo, metadata)
    if path.stat().st_size > PYTHON_LIMIT:
        raise LayoutError('Catalog metadata exceeds 256 KiB')
    entries = json.loads(path.read_text())
    if not isinstance(entries, list):
        raise LayoutError('Catalog metadata must be a list')
    by_name = {record['canonical_path']: record for record in records}
    seen = set()
    for entry in entries:
        fields = {'canonical_path', 'role', 'title', 'title_source'}
        if not isinstance(entry, dict) or set(entry) != fields:
            raise LayoutError(f'Catalog metadata requires exactly {sorted(fields)}')
        name, role = entry['canonical_path'], entry['role']
        if not isinstance(name, str) or name not in by_name or name in seen:
            raise LayoutError(f'Duplicate or untracked catalog path: {name!r}')
        seen.add(name)
        if role not in ROLES:
            raise LayoutError(f'Invalid catalog role: {role!r}')
        record = by_name[name]
        if record['role'] == 'fixture' and role == 'entry':
            raise LayoutError(f'Fixture cannot be promoted to entry: {name}')
        source, title = entry['title_source'], entry['title']
        if not isinstance(source, str) or source not in tracked:
            raise LayoutError(f'Untracked title source: {source!r}')
        if (not isinstance(title, str) or not title.strip() or len(title) > 240
                or any(ord(char) < 32 for char in title)):
            raise LayoutError(f'Invalid catalog title: {name}')
        source_path = safe_file(repo, source)
        source_text = read_prefix(source_path)
        if source_text.startswith(INDEX_MARKER):
            raise LayoutError(f'Generated inventory is not independent title evidence: {source}')
        evidence = source_text if source_path.suffix.lower() == '.md' else header_title(source_path, source_text) or ''
        if source == metadata or ' '.join(title.split()) not in ' '.join(evidence.split()):
            raise LayoutError(f'Title is not verbatim in source header: {name}')
        record.update(role=role, title=title, title_source=source)


def markdown(records):
    lines = ['# Test code index', '',
             'Generated by `python3 tools/test_catalog.py write-index` from Git tracked tests.',
             'Entry identifies a standalone script or reviewed metadata; read its requirements before running.',
             'Titles quote a file header or directory README; a missing title source means purpose is unknown.',
             'This inventory contains no execution results, requirements or inferred commands.', '']
    previous = None
    for record in records:
        if record['module'] != previous:
            previous = record['module']
            lines.extend([f'## {previous}', ''])
        title = record['title'].replace('`', "'").replace('\n', ' ')
        name = record['canonical_path']
        lines.append(f"- `{name}` — {title} ({record['role']}).")
        if record['logical_path']:
            lines.append(f"  Logical: `{record['logical_path']}`.")
        if record['title_source']:
            lines.append(f"  Title source: `{record['title_source']}`.")
    return '\n'.join(lines) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, default=Path(__file__).resolve().parents[1])
    commands = parser.add_subparsers(dest='action', required=True)
    query = commands.add_parser('query', help='Case-insensitive AND search over paths, titles and roles')
    query.add_argument('terms', nargs='*')
    query.add_argument('--module', help='Exact family, e.g. network or storage')
    query.add_argument('--role', choices=ROLES)
    query.add_argument('--json', action='store_true')
    check = commands.add_parser('check', help='Validate tracked sources and optional generated index')
    check.add_argument('--index', help='Compare a repository-relative generated Markdown index')
    write = commands.add_parser('write-index', help='Write an optional Markdown snapshot')
    write.add_argument('--index', default='tests/TEST_CODE_INDEX.md')
    args = parser.parse_args(argv)
    try:
        records = build_catalog(args.repo)
        if args.action == 'query':
            found = [r for r in records
                     if (not args.module or r['module'] == args.module)
                     and (not args.role or r['role'] == args.role)
                     and all(term.casefold() in ' '.join(str(v or '') for v in r.values()).casefold()
                             for term in args.terms)]
            if args.json:
                print(json.dumps(found, indent=2, ensure_ascii=False))
            else:
                for record in found:
                    print(f"{record['canonical_path']} [{record['module']}/{record['role']}] {record['title']}")
                    print(f"  logical: {record['logical_path'] or 'unknown'}; title source: {record['title_source'] or 'unknown'}")
            return 0 if found else 1
        if args.action == 'write-index':
            destination = safe_file(args.repo.resolve(), args.index, required=False)
            if not args.index.startswith('tests/') or destination.suffix != '.md':
                raise LayoutError('Index output must be a Markdown file beneath tests/')
            if destination.exists() and not read_prefix(destination).startswith(INDEX_MARKER):
                raise LayoutError('Refusing to overwrite an authored file with a generated index')
            tracked_output = subprocess.run(
                ['git', '-C', str(args.repo), 'ls-files', '-z', '--', args.index],
                check=True, capture_output=True).stdout
            if tracked_output and args.index != 'tests/TEST_CODE_INDEX.md':
                raise LayoutError('Refusing to overwrite a tracked source with a generated index')
            destination.write_text(markdown(records))
            print(f'Wrote {len(records)} paths to {args.index}')
        elif args.index:
            path = safe_file(args.repo.resolve(), args.index)
            if path.read_text() != markdown(records):
                raise LayoutError(f'Stale test code index: {args.index}')
            print(f'Validated {len(records)} tracked test paths and index')
        else:
            print(f'Validated {len(records)} tracked test paths; no tests executed')
        return 0
    except (LayoutError, OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f'test_catalog: {error}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
