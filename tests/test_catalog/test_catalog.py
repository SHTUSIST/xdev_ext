#!/usr/bin/env python3
"""Test code catalog: tracked discovery, evidence-backed labels and safe queries."""
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools'))


class CatalogTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='catalog-fixture-', dir=ROOT / 'tests/test_catalog')
        self.addCleanup(self.temp.cleanup)
        self.repo = Path(self.temp.name)
        self.git('init', '-q')
        self.put('tests/network/README.md', '# Network admission checks\n')
        self.put('tests/network/run.py', '#!/usr/bin/env python3\n"""Verify queue ownership after completion."""\nif __name__ == "__main__":\n    pass\n')
        self.put('tests/network/fixtures/run.py', '#!/usr/bin/env python3\nif __name__ == "__main__":\n    pass\n')
        self.put('tests/network/plain.c', 'int main(void) { return 0; }\n')
        self.put('source-layout.json', json.dumps({'schema': 1, 'files': [{'source': 'tests/network/run.py', 'logical_path': 'tests/selftests/run.py'}]}))
        self.git('add', '.')
        self.put('tests/network/not_tracked.py', '"""Never discover me."""\n')

    def git(self, *args):
        return subprocess.run(['git', '-C', str(self.repo), *args], check=True, capture_output=True)

    def put(self, name, data):
        path = self.repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(data)

    def catalog(self):
        spec = importlib.util.spec_from_file_location('test_catalog_tool', ROOT / 'tools/test_catalog.py')
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module.build_catalog(self.repo)

    def test_tracked_only_logical_paths_and_verbatim_titles(self):
        records = {r['canonical_path']: r for r in self.catalog()}
        self.assertNotIn('tests/network/not_tracked.py', records)
        record = records['tests/network/run.py']
        self.assertEqual(record['logical_path'], 'tests/selftests/run.py')
        self.assertEqual(record['title'], 'Verify queue ownership after completion.')
        self.assertEqual(record['title_source'], 'tests/network/run.py')
        self.assertEqual(record['module'], 'network')
        self.assertEqual(record['role'], 'entry')

    def test_c_block_opening_line_is_used_instead_of_directory_fallback(self):
        for header in ('/* Verify native descriptor retirement. */\n',
                       '/* Verify native descriptor retirement.\n * Additional detail.\n */\n',
                       '/* SPDX-License-Identifier: GPL-2.0-only */\n/* Verify native descriptor retirement. */\n'):
            self.put('tests/network/plain.c', header+'int main(void) { return 0; }\n')
            with self.subTest(header=header):
                record = {r['canonical_path']: r for r in self.catalog()}['tests/network/plain.c']
                self.assertEqual(record['title'], 'Verify native descriptor retirement.')
                self.assertEqual(record['title_source'], 'tests/network/plain.c')

    def test_c_preprocessor_is_not_a_description(self):
        for suffix in ('.c', '.cu', '.cuh', '.c.in'):
            name='tests/network/plain'+suffix
            self.put(name, '// SPDX-License-Identifier: GPL-2.0-only\n#include <errno.h>\n')
            self.git('add', name)
            with self.subTest(suffix=suffix):
                record = {r['canonical_path']: r for r in self.catalog()}[name]
                self.assertEqual(record['title'], 'Network admission checks')
                self.assertEqual(record['title_source'], 'tests/network/README.md')

    def test_generated_index_cannot_supply_title_evidence(self):
        self.put('tests/TEST_CODE_INDEX.md', '# Test code index\n\nGenerated by `python3 tools/test_catalog.py write-index`\n')
        self.git('add', 'tests/TEST_CODE_INDEX.md')
        self.metadata([{'canonical_path': 'tests/network/plain.c', 'role': 'entry',
                       'title': 'Test code index', 'title_source': 'tests/TEST_CODE_INDEX.md'}])
        with self.assertRaises(ValueError):
            self.catalog()

    def test_fixture_wins_and_unknown_c_has_no_execution_claim(self):
        records = {r['canonical_path']: r for r in self.catalog()}
        self.assertEqual(records['tests/network/fixtures/run.py']['role'], 'fixture')
        unknown = records['tests/network/plain.c']
        self.assertEqual(unknown['role'], 'unknown')
        self.assertEqual(unknown['title'], 'Network admission checks')
        self.assertEqual(unknown['title_source'], 'tests/network/README.md')
        self.assertIsNone(unknown['logical_path'])
        self.assertTrue({'command', 'result', 'environment', 'status'}.isdisjoint(unknown))

    def metadata(self, records):
        self.put('tests/test_catalog/entries.json', json.dumps(records))
        self.git('add', 'tests/test_catalog/entries.json')

    def test_rejects_tracked_symlink_and_missing_file(self):
        source = self.repo / 'tests/network/plain.c'
        source.unlink()
        with self.assertRaises(ValueError):
            self.catalog()
        source.symlink_to(self.repo / 'source-layout.json')
        with self.assertRaises(ValueError):
            self.catalog()

    def test_rejects_unsafe_layout_path(self):
        self.put('source-layout.json', json.dumps({'schema': 1, 'files': [
            {'source': 'tests/../secret', 'logical_path': 'tests/x'}]}))
        with self.assertRaises(ValueError):
            self.catalog()

    def test_curated_title_must_have_tracked_verbatim_source(self):
        self.metadata([{'canonical_path': 'tests/network/plain.c', 'role': 'entry',
                       'title': 'Network admission checks', 'title_source': 'tests/network/README.md'}])
        record = {r['canonical_path']: r for r in self.catalog()}['tests/network/plain.c']
        self.assertEqual(record['role'], 'entry')
        self.assertEqual(record['title_source'], 'tests/network/README.md')
        for field, value in [('title', 'An invented purpose'),
                             ('canonical_path', 'tests/network/missing.c'),
                             ('canonical_path', '../outside'),
                             ('title_source', 'tests/network/not_tracked.py'),
                             ('role', 'PASS')]:
            entry = {'canonical_path': 'tests/network/plain.c', 'role': 'entry',
                     'title': 'Network admission checks', 'title_source': 'tests/network/README.md'}
            entry[field] = value
            self.metadata([entry])
            with self.subTest(field=field), self.assertRaises(ValueError):
                self.catalog()

    def test_fixture_cannot_be_promoted_by_metadata(self):
        self.metadata([{'canonical_path': 'tests/network/fixtures/run.py', 'role': 'entry',
                       'title': 'Network admission checks', 'title_source': 'tests/network/README.md'}])
        with self.assertRaises(ValueError):
            self.catalog()

    def cli(self, *args):
        return subprocess.run([sys.executable, str(ROOT / 'tools/test_catalog.py'),
                               '--repo', str(self.repo), *args], capture_output=True, text=True)

    def test_cli_search_validation_and_stale_index(self):
        found = self.cli('query', 'queue', '--json')
        self.assertEqual(found.returncode, 0, found.stderr)
        self.assertEqual(len(json.loads(found.stdout)), 1)
        self.assertEqual(self.cli('query', 'no-such-purpose').returncode, 1)
        self.assertEqual(self.cli('check').returncode, 0)
        self.assertEqual(self.cli('write-index').returncode, 0)
        self.assertEqual(self.cli('check', '--index', 'tests/TEST_CODE_INDEX.md').returncode, 0)
        with (self.repo / 'tests/TEST_CODE_INDEX.md').open('a') as stream:
            stream.write('stale')
        self.assertEqual(self.cli('check', '--index', 'tests/TEST_CODE_INDEX.md').returncode, 2)
        self.assertEqual(self.cli('write-index', '--index', '../outside.md').returncode, 2)
        self.assertEqual(self.cli('query', '--module', 'storage', '--json').returncode, 1)
        self.assertEqual(self.cli('query', '--role', 'entry', '--json').returncode, 0)

    def test_index_regenerates_after_tracking_without_overwriting_source(self):
        self.assertEqual(self.cli('write-index').returncode, 0)
        self.git('add', 'tests/TEST_CODE_INDEX.md')
        self.assertEqual(self.cli('write-index').returncode, 0)
        self.assertEqual(self.cli('check', '--index', 'tests/TEST_CODE_INDEX.md').returncode, 0)
        before = (self.repo / 'source-layout.json').read_bytes()
        rejected = self.cli('write-index', '--index', 'source-layout.json')
        self.assertEqual(rejected.returncode, 2)
        self.assertEqual((self.repo / 'source-layout.json').read_bytes(), before)
        before = (self.repo / 'tests/network/README.md').read_bytes()
        self.assertEqual(self.cli('write-index', '--index', 'tests/network/README.md').returncode, 2)
        self.assertEqual((self.repo / 'tests/network/README.md').read_bytes(), before)

    def test_write_index_preserves_untracked_authored_files(self):
        for target in ('tests/network/new.py', 'tests/network/notes.md', 'tests/TEST_CODE_INDEX.md'):
            self.put(target, 'Authored text must survive.\n')
            before = (self.repo / target).read_bytes()
            self.assertEqual(self.cli('write-index', '--index', target).returncode, 2)
            self.assertEqual((self.repo / target).read_bytes(), before)

    def test_metadata_cannot_supply_its_own_title_evidence(self):
        self.metadata([{'canonical_path': 'tests/network/plain.c', 'role': 'entry',
                       'title': 'Invented purpose', 'title_source': 'tests/test_catalog/entries.json'}])
        with self.assertRaises(ValueError):
            self.catalog()


if __name__ == '__main__':
    unittest.main()
