"""Execute the resolver actually selected by each mechanism verifier table.

Requirement TODO.27-a: shared classes delegate only lookup/time; XDOMAIN only
lookup. Break caught: any other helper reaches upstream, including a resolver
which delegates but discards upstream's return. The upstream resolver alone is
stubbed; the selected production resolver and table initializer are real.
This is host boundary evidence, not kernel verifier acceptance.
"""
import os
